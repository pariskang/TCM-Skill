def to_traditional(text: str, client=None) -> str:
    """把可能含简体的文本转为繁体。优先 opencc,其次内置表。

    LLM 转换见 to_traditional_llm(单独调用,避免逐段翻译开销)。
    """
    if not text:
        return text
    cc = _opencc()
    if cc is not None:
        try:
            return cc.convert(text)
        except Exception:
            pass
    return "".join(SIMP2TRAD.get(c, c) for c in text)


def looks_simplified(text: str) -> bool:
    return any(c in SIMP2TRAD for c in text)


def to_traditional_llm(text: str, client) -> Optional[str]:
    """用 LLM 将查询转为繁体(语义级,处理一简多繁)。失败返回 None。"""
    if client is None:
        return None
    try:
        sys = ("你是简繁转换器。把用户文本转成繁体中文(台湾/传统用字),"
               "只做字形转换、保留原意与术语,一简对多繁时按中医语境选字。")
        out = client.complete(sys, f"转为繁体,只输出结果:\n{text}")
        return (out or "").strip() or None
    except Exception:
        return None
